const english = new Map(labels);
const korean = new Map(labels.map(([ko,en])=>[en,ko]));

export function useSettingsLanguage() {
  const [language,setLanguage] = useState(()=>{
    try { return localStorage.getItem(storageKey)==="ko" ? "ko" : "en" } catch { return "en" }
  });
  function changeLanguage(value) {
    setLanguage(value);
    try {localStorage.setItem(storageKey,value)} catch {}
  }
  function t(text) {
    return (language==="ko"?korean:english).get(text) ?? text;
  }
  return {language,changeLanguage,t};
}
